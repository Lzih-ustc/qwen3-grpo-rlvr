#!/usr/bin/env python3
"""Build the locked, generated Math Dataset train/validation/test splits.

The questions are generated by the pinned DeepMind Mathematics Dataset source.
Only samples with an integer answer and a prompt length within the upstream
generator's published bound are retained so the existing exact-integer verifier
can score every item. The output is written only when all split checks pass.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
import random
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Callable

import numpy as np


ROOT = Path(__file__).resolve().parents[3]
GENERATOR_URL = "https://github.com/google-deepmind/mathematics_dataset.git"
GENERATOR_COMMIT = "427f45075f84b8b9774950196ad63867ca20ffb3"
SPLITS = {
    "train": {"regime": "train", "seed": 260101, "count": 1500},
    "validation": {"regime": "interpolate", "seed": 260102, "count": 300},
    "test": {"regime": "extrapolate", "seed": 260103, "count": 500},
}
INTEGER_ANSWER = re.compile(r"[+-]?\d+\Z")
PROMPT_PREFIX = (
    "Solve this math problem. Show concise work and put the final integer "
    "inside <answer>...</answer>.\n\n"
)


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def normalized_question(text: str) -> str:
    return " ".join(text.casefold().split())


def flatten_modules(tree: dict[str, Any], prefix: str = "") -> dict[str, Callable[[], Any]]:
    flattened: dict[str, Callable[[], Any]] = {}
    for key, value in sorted(tree.items()):
        name = f"{prefix}/{key}" if prefix else key
        if isinstance(value, dict):
            flattened.update(flatten_modules(value, name))
        elif callable(value):
            flattened[name] = value
        else:
            raise TypeError(f"Unexpected module leaf at {name}: {type(value).__name__}")
    if not flattened and not prefix:
        raise ValueError("No generator functions found in the requested regime")
    return flattened


def load_source(source_dir: Path):
    source_dir = source_dir.resolve()
    if not (source_dir / "mathematics_dataset" / "modules" / "modules.py").is_file():
        raise FileNotFoundError(f"Pinned generator source is missing: {source_dir}")
    revision = subprocess.check_output(
        ["git", "-C", str(source_dir), "rev-parse", "HEAD"], text=True
    ).strip()
    if revision != GENERATOR_COMMIT:
        raise RuntimeError(f"Generator revision mismatch: expected {GENERATOR_COMMIT}, got {revision}")
    sys.path.insert(0, str(source_dir))
    from mathematics_dataset.modules import modules  # noqa: PLC0415

    from mathematics_dataset import generate_settings  # noqa: PLC0415

    license_path = source_dir / "LICENSE"
    if not license_path.is_file():
        raise FileNotFoundError("Pinned generator LICENSE file is missing")
    return modules, generate_settings, license_path


def get_regime(modules: Any, name: str) -> dict[str, Callable[[], Any]]:
    if name == "train":
        tree = modules.train(lambda entropy_range: entropy_range)
    elif name == "interpolate":
        tree = modules.test()
    elif name == "extrapolate":
        tree = modules.test_extra()
    else:
        raise ValueError(f"Unknown generator regime: {name}")
    flattened = flatten_modules(tree)
    # The upstream composition helper builds a set of identity-hashed Entity
    # objects before shuffling them. That makes descriptions differ across
    # processes even with fixed Python/NumPy seeds. Exclude those modules rather
    # than patching upstream behavior or pretending the output is bitwise stable.
    deterministic = {key: value for key, value in flattened.items() if "_composed" not in key}
    if not deterministic:
        raise ValueError(f"No deterministic generator leaves remain in {name}")
    return deterministic


def generate_split(
    *,
    name: str,
    modules: dict[str, Callable[[], Any]],
    seed: int,
    count: int,
    max_question_chars: int,
    max_answer_chars: int,
    globally_seen: set[str],
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    random.seed(seed)
    np.random.seed(seed)
    module_rng = random.Random(seed ^ 0x5EED2026)
    module_names = sorted(modules)
    rows: list[dict[str, Any]] = []
    attempts = 0
    rejected = Counter()
    module_counts: Counter[str] = Counter()
    local_seen: set[str] = set()
    max_attempts = max(100_000, count * 2_000)

    while len(rows) < count and attempts < max_attempts:
        attempts += 1
        module_name = module_names[module_rng.randrange(len(module_names))]
        try:
            problem = modules[module_name]()
        except TypeError as exc:
            # The upstream 2019 generator contains a small number of
            # random.randint(float, float) calls that CPython 3.12 rejects.
            # Do not patch the generator silently: skip only that known runtime
            # incompatibility and record its frequency in the lock manifest.
            if "float' object cannot be interpreted as an integer" not in str(exc):
                raise
            rejected["upstream_cpython_312_float_randint"] += 1
            continue
        question = str(problem.question).strip()
        answer = str(problem.answer).strip()
        if len(question) > max_question_chars:
            rejected["question_too_long"] += 1
            continue
        if len(answer) > max_answer_chars or not INTEGER_ANSWER.fullmatch(answer):
            rejected["non_integer_or_long_answer"] += 1
            continue
        key = normalized_question(question)
        if not key or key in local_seen or key in globally_seen:
            rejected["duplicate_question"] += 1
            continue
        local_seen.add(key)
        globally_seen.add(key)
        module_counts[module_name] += 1
        rows.append({
            "prompt": [{
                "role": "user",
                "content": PROMPT_PREFIX + question,
            }],
            "answer": answer,
            "meta": {
                "dataset": "DeepMind Mathematics Dataset generated subset",
                "regime": name,
                "generator_module": module_name,
                "seed": seed,
                "source_question_sha256": sha256_bytes(question.encode("utf-8")),
                "source_question": question,
            },
        })

    if len(rows) != count:
        raise RuntimeError(
            f"Could not fill {name}: wanted {count}, got {len(rows)} after {attempts} attempts; "
            f"rejections={dict(rejected)}"
        )
    report = {
        "regime": name,
        "seed": seed,
        "count": len(rows),
        "attempts": attempts,
        "rejections": dict(sorted(rejected.items())),
        "modules": dict(sorted(module_counts.items())),
    }
    return rows, report


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> str:
    payload = "".join(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in rows)
    data = payload.encode("utf-8")
    path.write_bytes(data)
    return sha256_bytes(data)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=ROOT / ".cache" / "efficient_rlvr" / "math_dataset_src",
        help="Local clone at the pinned upstream commit",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "data" / "efficient-rlvr-math-v1",
    )
    args = parser.parse_args()
    hash_seed = os.environ.get("PYTHONHASHSEED")
    if hash_seed != "0":
        raise SystemExit("Set PYTHONHASHSEED=0 before starting Python to make upstream set iteration deterministic")
    modules, generate_settings, license_path = load_source(args.source_dir)
    final_dir = args.output_dir.resolve()
    final_dir.parent.mkdir(parents=True, exist_ok=True)
    if final_dir.exists() and any(final_dir.iterdir()):
        raise SystemExit(f"Refusing to overwrite locked data: {final_dir}")
    output_dir = final_dir.with_name(final_dir.name + ".staging")
    if output_dir.exists() and any(output_dir.iterdir()):
        raise SystemExit(f"Refusing to overwrite an existing staging directory: {output_dir}")
    output_dir.mkdir(parents=True, exist_ok=True)

    globally_seen: set[str] = set()
    split_reports: dict[str, Any] = {}
    split_hashes: dict[str, str] = {}
    for split_name, spec in SPLITS.items():
        regime_modules = get_regime(modules, spec["regime"])
        rows, report = generate_split(
            name=split_name,
            modules=regime_modules,
            seed=spec["seed"],
            count=spec["count"],
            max_question_chars=int(generate_settings.MAX_QUESTION_LENGTH),
            max_answer_chars=int(generate_settings.MAX_ANSWER_LENGTH),
            globally_seen=globally_seen,
        )
        split_hashes[split_name] = write_jsonl(output_dir / f"{split_name}.jsonl", rows)
        split_reports[split_name] = report

    license_bytes = license_path.read_bytes()
    (output_dir / "UPSTREAM-LICENSE.txt").write_bytes(license_bytes)
    total = sum(int(spec["count"]) for spec in SPLITS.values())
    manifest = {
        "dataset_id": "efficient-rlvr-math-v1",
        "created_utc": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(),
        "status": "locked; post-training candidate selection may use train and validation only",
        "source": {
            "name": "DeepMind Mathematics Dataset v1.0 generator",
            "repository": GENERATOR_URL,
            "revision": GENERATOR_COMMIT,
            "license": "Apache-2.0 for upstream generator code; upstream does not separately state generated-output licensing",
            "license_sha256": sha256_bytes(license_bytes),
            "paper": "Saxton et al., Analysing Mathematical Reasoning Abilities of Neural Models (2019), https://openreview.net/forum?id=H1gR5iR5FX",
        },
        "generation": {
            "selection": "integer-answer rows only; no hand editing; exact normalized prompt duplicates rejected across all splits",
            "answer_format": "signed base-10 integer; compatible with scripts.math_task exact integer verifier",
            "prompt_wrapper": PROMPT_PREFIX,
            "max_question_chars": int(generate_settings.MAX_QUESTION_LENGTH),
            "max_answer_chars": int(generate_settings.MAX_ANSWER_LENGTH),
            "python": sys.version.split()[0],
            "python_hash_seed": 0,
            "numpy": np.__version__,
            "sympy": importlib.metadata.version("sympy"),
            "absl_py": importlib.metadata.version("absl-py"),
            "six": importlib.metadata.version("six"),
            "sampling_policy": "uniform choice over sorted non-composed generator leaf modules with independent module-choice RNG; Python random and NumPy RNG seeded per split",
            "upstream_nondeterminism_control": "Exclude upstream leaf names containing _composed because their entity descriptions iterate a set of identity-hashed objects; no upstream source patch is applied.",
            "python_compatibility": "On CPython 3.12, skip generator calls that raise the known upstream random.randint(float, float) TypeError; no upstream source edits or altered random draws are applied.",
            "historical_data_policy": "GSM8K and SVAMP consumed test sets are not used here; no model-generated output or historical result is used to accept, reject, rank, or tune samples beyond exact prompt deduplication",
        },
        "historical_exposure_limits": [
            "The repo's recorded training, validation, and evaluation data were searched for exact normalized source-question matches before lock.",
            "No claim is made that Qwen3 pretraining never encountered the public generator or related problem forms.",
        ],
        "splits": {
            name: {
                **split_reports[name],
                "file": f"{name}.jsonl",
                "sha256": split_hashes[name],
                "selection_role": {
                    "train": "RLVR training only",
                    "validation": "interpolation validation; candidate selection and hyperparameters may inspect this split",
                    "test": "extrapolation independent test; sealed from all candidate selection",
                }[name],
            }
            for name in SPLITS
        },
        "total_rows": total,
        "unique_normalized_source_questions": len(globally_seen),
        "test_access_policy": "Do not use for checkpoint, reward coefficient, group-size, stopping, or prompt selection. Open once after all choices are frozen.",
    }
    (output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    if final_dir.exists():
        final_dir.rmdir()
    output_dir.replace(final_dir)
    print(json.dumps({"output_dir": str(final_dir), "manifest": manifest}, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
